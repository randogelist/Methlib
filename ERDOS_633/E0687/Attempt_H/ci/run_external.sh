#!/usr/bin/env bash
set -euo pipefail
ATTEMPT="$(cd "$(dirname "$0")/.." && pwd)"
ROOT="$(cd "$ATTEMPT/../../.." && pwd)"
OPENAI="$ROOT/.ci-openai/lean"
REF="$ROOT/.ci-referee/970/openai-jacobsthal-quadratic-refereed/bridge687"
EVIDENCE="$ATTEMPT/evidence/external"
mkdir -p "$EVIDENCE"
test "$(git -C "$ROOT/.ci-openai" rev-parse HEAD)" = "1581d4cbdd69a0faf34b2089614fe2a814316a6a"
test "$(git -C "$ROOT/.ci-referee" rev-parse HEAD)" = "634b667ee7844f12590117c4c2d7bc0143f2fdd9"
test "$(git hash-object "$REF/Bridge687.lean")" = "64a1cf3ff88a4f655ae7284aa3fb99ed9eab4932"
test "$(cat "$OPENAI/lean-toolchain")" = "leanprover/lean4:v4.34.1"
cd "$OPENAI"
lean --version | tee "$EVIDENCE/lean-version.log"
lake update 2>&1 | tee "$EVIDENCE/lake-update.log"
test "$(git -C .lake/packages/mathlib rev-parse HEAD)" = "d13f23b723b8a846827a245b89c10fc7d3f11612"
lake exe cache get 2>&1 | tee "$EVIDENCE/mathlib-cache.log"
test -s .lake/packages/mathlib/.lake/build/lib/lean/Mathlib.olean || lake build Mathlib
lake build OAI.NumberTheory.Jacobsthal.Main 2>&1 | tee "$EVIDENCE/jacobsthal-build.log"
lake env bash -c 'export LEAN_PATH="$1:$LEAN_PATH"; lean --trust=0 -o "$1/Bridge687.olean" "$1/Bridge687.lean"' _ "$REF" 2>&1 | tee "$EVIDENCE/bridge-build.log"
lake env bash -c 'export LEAN_PATH="$1:$2:$LEAN_PATH"; lean --trust=0 -o "$1/Erdos687AttemptHExternal.olean" "$1/Erdos687AttemptHExternal.lean"' _ "$ATTEMPT" "$REF" 2>&1 | tee "$EVIDENCE/build.log"
lake env bash -c 'export LEAN_PATH="$1:$2:$LEAN_PATH"; lean --trust=0 "$1/AuditExternal.lean"' _ "$ATTEMPT" "$REF" 2>&1 | tee "$EVIDENCE/axiom-audit.log"
python3 "$ATTEMPT/ci/check_axioms.py" external "$EVIDENCE/axiom-audit.log" | tee "$EVIDENCE/audit-verdict.log"
echo "H_EXISTING_EXTERNAL_ERDOS_687_PART_II=PASS" | tee "$EVIDENCE/final-status.txt"
